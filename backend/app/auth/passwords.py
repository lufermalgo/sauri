"""Password hashing and verification for the minimal User store.

Uses PBKDF2-HMAC-SHA256 (stdlib `hashlib`) to avoid a new dependency. Not
an integration with Summan's IdP (Req. 13.1, 13.2).
"""

from __future__ import annotations

import hashlib
import hmac
import os

_ITERATIONS = 260_000
_ALGORITHM = "pbkdf2_sha256"


def hash_password(password: str) -> str:
    """Generates a hash with a random salt: '<algorithm>$<iterations>$<salt>$<hash>'."""
    salt = os.urandom(16)
    derived = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, _ITERATIONS)
    return f"{_ALGORITHM}${_ITERATIONS}${salt.hex()}${derived.hex()}"


def verify_password(password: str, password_hash: str) -> bool:
    """Verifies a password against a hash generated by `hash_password`."""
    try:
        algorithm, iterations_str, salt_hex, hash_hex = password_hash.split("$")
        if algorithm != _ALGORITHM:
            return False
        iterations = int(iterations_str)
        salt = bytes.fromhex(salt_hex)
        expected = bytes.fromhex(hash_hex)
    except (ValueError, AttributeError):
        return False

    derived = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, iterations)
    return hmac.compare_digest(derived, expected)
